#!/usr/bin/env bash
# Drive training on the BSC cluster from your own machine (ssh + rsync + sbatch).
#
#   ./bsc.sh help                       full workflow
#   DRY_RUN=1 ./bsc.sh <command> ...    print every ssh/rsync command instead of running it
set -euo pipefail

HERE="$(cd "$(dirname "${BASH_SOURCE[0]}")" && pwd)"
CODE_DIR="$(cd "$HERE/../.." && pwd)"        # .../TFG/code
STAGE="${STAGE_DIR:-$HERE/.stage}"           # wheelhouse + model weights, built locally
CONFIG="${BSC_CONFIG:-$HERE/config.sh}"
DRY_RUN="${DRY_RUN:-}"

die() { echo "error: $*" >&2; exit 1; }

usage() {
  cat <<'EOF'
Workflow (the cluster has NO internet, so everything is staged from here first):

  cp config.example.sh config.sh       # fill in account, QOS, paths; see `bsc_project list`, `bsc_queues`
  ./bsc.sh build                       # download wheels + Stable Diffusion + detector weights  (needs internet)
  ./bsc.sh push code                   # source + remote.env              -> $REMOTE_CODE
  ./bsc.sh push stage                  # wheelhouse + weights             -> $REMOTE_WORK
  ./bsc.sh push data polyp_synth/raw   # datasets under code/data/<dir>   -> $REMOTE_WORK/data/<dir>
  ./bsc.sh setup                       # builds the virtualenv on a compute node from the wheelhouse

  ./bsc.sh submit <job> [sbatch flags] [-- job args]     jobs: lora_train generate gate downstream detectors optuna
  ./bsc.sh pipeline                    # lora_train -> generate -> gate -> downstream (afterok chain)
  ./bsc.sh status | logs [jobid] | cancel <jobid>
  ./bsc.sh pull polyp_synth/downstream/full              # results: $REMOTE_WORK/out/<dir> -> code/out/<dir>

Examples:
  ./bsc.sh submit lora_train --time=04:00:00 -- --steps 6000 --no-grad-ckpt
  ARMS="real neg synth" SEEDS="0 1 2 3 4" ./bsc.sh pipeline
  ./bsc.sh submit optuna --time=24:00:00 --qos=<your-long-queue> -- --n-trials 30
EOF
}

load_config() {
  [ -f "$CONFIG" ] || die "missing $CONFIG - copy config.example.sh to config.sh and fill it in"
  # shellcheck disable=SC1090
  source "$CONFIG"
  local v
  for v in BSC_USER BSC_ACCOUNT BSC_QOS BSC_LOGIN BSC_TRANSFER REMOTE_CODE REMOTE_WORK GRES CPUS_PER_JOB \
           PYTHON_MODULE PYTHON_VERSION PIP_PLATFORMS TORCH_INDEX TORCH_SPEC LOCAL_PYTHON; do
    [ -n "${!v:-}" ] || die "$v is not set in $CONFIG"
    case "${!v}" in *'<'*) die "$v still contains a <placeholder> in $CONFIG" ;; esac
  done
}

# Echo a command in dry-run mode, run it otherwise.
run() {
  if [ -n "$DRY_RUN" ]; then printf '+'; printf ' %q' "$@"; printf '\n'; else "$@"; fi
}

# Run a shell command line on the login node.
remote() { run ssh "$BSC_USER@$BSC_LOGIN" "$1"; }

# REMOTE_CODE / REMOTE_WORK may contain $HOME. ssh would expand it, but rsync >= 3.2.4 does not expand
# remote paths any more (it would create a directory literally named "$HOME"), so resolve them once.
resolve_remote_paths() {
  if [ -n "$DRY_RUN" ]; then return 0; fi
  local out
  # shellcheck disable=SC2029  # the config values are meant to be inserted here and expanded by the remote shell
  out="$(ssh "$BSC_USER@$BSC_LOGIN" "echo $REMOTE_CODE; echo $REMOTE_WORK")" || die "cannot reach $BSC_LOGIN over ssh"
  REMOTE_CODE="$(sed -n 1p <<<"$out")"
  REMOTE_WORK="$(sed -n 2p <<<"$out")"
  [[ "$REMOTE_CODE" == /* && "$REMOTE_WORK" == /* ]] || die "could not resolve remote paths: '$out'"
}

sbatch_flags() {
  printf '%s' "--account=$BSC_ACCOUNT --qos=$BSC_QOS --gres=$GRES --cpus-per-task=$CPUS_PER_JOB"
  [ -z "${BSC_PARTITION:-}" ] || printf ' %s' "--partition=$BSC_PARTITION"
}

write_remote_env() {
  local tmp
  tmp="$(mktemp)"
  {
    echo "# generated by bsc.sh from config.sh - do not edit"
    printf 'BSC_CODE="%s"\n' "$REMOTE_CODE"
    printf 'BSC_WORK="%s"\n' "$REMOTE_WORK"
    printf 'BSC_VENV="%s/venv"\n' "$REMOTE_CODE"
    printf 'BSC_PYTHON_MODULE="%s"\n' "$PYTHON_MODULE"
    printf 'BSC_EXTRA_MODULES="%s"\n' "${EXTRA_MODULES:-}"
    printf 'BSC_TORCH_SPEC="%s"\n' "$TORCH_SPEC"
  } >"$tmp"
  echo "$tmp"
}

cmd_build() {
  run mkdir -p "$STAGE/wheelhouse" "$STAGE/hf" "$STAGE/torch"
  echo "== wheelhouse for python $PYTHON_VERSION ($PIP_PLATFORMS) -> $STAGE/wheelhouse"
  local platform_args=() p
  for p in $PIP_PLATFORMS; do platform_args+=(--platform "$p"); done
  # shellcheck disable=SC2086  # TORCH_SPEC is a deliberate list of requirement specifiers
  run python3 -m pip download --dest "$STAGE/wheelhouse" --only-binary=:all: \
    --implementation cp --python-version "$PYTHON_VERSION" --abi "cp${PYTHON_VERSION/./}" "${platform_args[@]}" \
    --index-url "$TORCH_INDEX" --extra-index-url https://pypi.org/simple \
    -r "$HERE/requirements-hpc.txt" $TORCH_SPEC
  echo "== model weights -> $STAGE/hf, $STAGE/torch"
  run env HF_HOME="$STAGE/hf" TORCH_HOME="$STAGE/torch" "$LOCAL_PYTHON" "$HERE/prefetch_weights.py"
  echo "built. next: ./bsc.sh push code && ./bsc.sh push stage && ./bsc.sh setup"
}

cmd_push() {
  local what="${1:-}"
  case "$what" in
    code)
      remote "mkdir -p $REMOTE_CODE/code/hpc/bsc/logs"
      run rsync -az --delete --human-readable \
        --exclude '__pycache__/' --exclude '*.pyc' --exclude '.stage/' --exclude 'config.sh' --exclude 'logs/' --exclude 'remote.env' \
        "$CODE_DIR/src" "$CODE_DIR/configurations" "$CODE_DIR/hpc" "$CODE_DIR/requirements.txt" "$CODE_DIR/requirements-synth.txt" \
        "$BSC_USER@$BSC_TRANSFER:$REMOTE_CODE/code/"
      local envfile
      envfile="$(write_remote_env)"
      run rsync -az "$envfile" "$BSC_USER@$BSC_TRANSFER:$REMOTE_CODE/code/hpc/bsc/remote.env"
      rm -f "$envfile"
      ;;
    stage)
      [ -d "$STAGE/wheelhouse" ] || [ -n "$DRY_RUN" ] || die "nothing staged: run ./bsc.sh build first"
      remote "mkdir -p $REMOTE_WORK/stage $REMOTE_WORK/hf $REMOTE_WORK/torch $REMOTE_WORK/data $REMOTE_WORK/out"
      run rsync -a --partial --human-readable --info=progress2 "$STAGE/wheelhouse/" "$BSC_USER@$BSC_TRANSFER:$REMOTE_WORK/stage/wheelhouse/"
      run rsync -a --partial --human-readable --info=progress2 "$STAGE/hf/" "$BSC_USER@$BSC_TRANSFER:$REMOTE_WORK/hf/"
      run rsync -a --partial --human-readable --info=progress2 "$STAGE/torch/" "$BSC_USER@$BSC_TRANSFER:$REMOTE_WORK/torch/"
      ;;
    data)
      local sub="${2:-}"
      [ -n "$sub" ] || die "usage: bsc.sh push data <dir under code/data>   e.g. polyp_synth/raw, TrainValid, Test"
      [ -d "$CODE_DIR/data/$sub" ] || die "no such directory: $CODE_DIR/data/$sub"
      remote "mkdir -p $REMOTE_WORK/data/$sub"
      # the negatives_gen/negatives_heldout symlink folders are rebuilt on the cluster by polyp_synth.split_negatives
      run rsync -a --partial --human-readable --info=progress2 --exclude 'negatives_gen/' --exclude 'negatives_heldout/' \
        "$CODE_DIR/data/$sub/" "$BSC_USER@$BSC_TRANSFER:$REMOTE_WORK/data/$sub/"
      ;;
    *) die "usage: bsc.sh push code | stage | data <dir>" ;;
  esac
}

# submit <job> [sbatch flags...] [-- job args...]
cmd_submit() {
  local job="${1:-}"
  [ -n "$job" ] || die "usage: bsc.sh submit <job> [sbatch flags] [-- job args]"
  shift
  [ -f "$HERE/jobs/$job.sbatch" ] || die "unknown job '$job' (see $HERE/jobs/)"
  local flags=() args=() seen_sep=""
  while [ "$#" -gt 0 ]; do
    if [ -z "$seen_sep" ] && [ "$1" = "--" ]; then seen_sep=1
    elif [ -n "$seen_sep" ]; then args+=("$1")
    else flags+=("$1")
    fi
    shift
  done
  local extra="" a
  for a in "${flags[@]+"${flags[@]}"}"; do extra+=" $(printf '%q' "$a")"; done
  local jobargs=""
  for a in "${args[@]+"${args[@]}"}"; do jobargs+=" $(printf '%q' "$a")"; done
  local envs="" v
  for v in RUN_NAME N_SYNTH SYNTH_NAME SEED ARMS SEEDS TAG KEEP_THR DEBUG N_TRIALS MAX_EPOCHS; do
    [ -z "${!v:-}" ] || envs+=" $v=$(printf '%q' "${!v}")"
  done
  remote "cd $REMOTE_CODE/code/hpc/bsc && mkdir -p logs && env$envs sbatch --parsable $(sbatch_flags)$extra jobs/$job.sbatch$jobargs"
}

cmd_setup() {
  echo "building the virtualenv on a compute node (login nodes have a 5 min CPU limit)..."
  cmd_submit setup_env --wait --time=00:40:00
}

cmd_pipeline() {
  local envs="" v
  for v in RUN_NAME N_SYNTH SYNTH_NAME SEED ARMS SEEDS TAG KEEP_THR; do
    [ -z "${!v:-}" ] || envs+=" $v=$(printf '%q' "${!v}")"
  done
  remote "cd $REMOTE_CODE/code/hpc/bsc && mkdir -p logs && env$envs SBATCH_FLAGS='$(sbatch_flags)' ./pipeline.sh"
}

cmd_status() { remote "squeue -u $BSC_USER -o '%.10i %.12P %.22j %.8T %.10M %.10l %.6D %R'"; }

cmd_logs() {
  local id="${1:-}"
  remote "cd $REMOTE_CODE/code/hpc/bsc/logs && f=\$(ls -t *${id}*.out 2>/dev/null | head -1) && echo \"== \$f\" && tail -n 40 \"\$f\""
}

cmd_cancel() { [ -n "${1:-}" ] || die "usage: bsc.sh cancel <jobid>"; remote "scancel $1"; }

cmd_pull() {
  local sub="${1:-}"
  [ -n "$sub" ] || die "usage: bsc.sh pull <dir under out/>   e.g. polyp_synth/downstream/full"
  run mkdir -p "$CODE_DIR/out/$sub"
  run rsync -az --partial --human-readable --info=progress2 "$BSC_USER@$BSC_TRANSFER:$REMOTE_WORK/out/$sub/" "$CODE_DIR/out/$sub/"
}

main() {
  local cmd="${1:-help}"
  [ "$#" -eq 0 ] || shift
  case "$cmd" in
    help|-h|--help) usage; return 0 ;;
  esac
  load_config
  [ "$cmd" = build ] || resolve_remote_paths
  case "$cmd" in
    build) cmd_build ;;
    push) cmd_push "$@" ;;
    setup) cmd_setup ;;
    submit) cmd_submit "$@" ;;
    pipeline) cmd_pipeline ;;
    status) cmd_status ;;
    logs) cmd_logs "$@" ;;
    cancel) cmd_cancel "$@" ;;
    pull) cmd_pull "$@" ;;
    *) usage; die "unknown command '$cmd'" ;;
  esac
}

main "$@"
